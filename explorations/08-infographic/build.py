class Poster:
    def __init__(self, data, expand_repeats=False):
        self.d = data
        self.expand = expand_repeats
        self.p = Project(W, H, ROLES["background"])
        self.ops = []

    def op(self, **kw):
        self.ops.append(kw)
        return kw

    def repeat(self, target, count, dx=0, dy=0):
        """Live `repeat` (one editable layer) or, for strict-SVG output, explicit duplicates."""
        if not self.expand:
            self.op(type="repeat", target=target, count=count, dx=dx, dy=dy)
            return [target]
        base = next(o for o in self.ops if o.get("name") == target)
        names = [target]
        for k in range(1, count):
            copy = {**base, "name": f"{target}-{k}", "x": base["x"] + k * dx, "y": base["y"] + k * dy}
            self.ops.append(copy)
            names.append(copy["name"])
        return names

    def flush(self):
        if self.ops:
            self.p.apply(self.ops, detail="compact")
            self.ops = []

    def text(self, name, text, style, x=0, y=0, color="@ink", font="body", align="left", spacing=None):
        o = self.op(type="text", name=name, text=text, x=x, y=y, color=color, font=font, align=align)
        if spacing is not None:
            o["spacing"] = spacing
        self.op(type="style-apply", target=name, name=style)
        return name

    def bounds(self, name):
        return self.p.inspect(name)["resolved_bounds"]

    # ---------------------------------------------------------------- setup
    def setup(self):
        p = self.p
        print("  installing fonts (Google Fonts, cached)...")
        pair_fonts(p, "dm-serif-dm-sans")
        install_font(p, "DM Sans", 700)  # registered as dm-sans-700
        install_font(p, "DM Mono", 500)  # registered as dm-mono-500
        self.op(type="palette-define", name="oi", colors=OKABE_ITO)
        self.op(type="palette-apply", name="oi", roles=False)
        for k, v in ROLES.items():
            self.op(type="swatch", name=k, color=v)
        # Modular type scale: caption 15 ... display 136 (perfect fourth from 21 px)
        self.op(type="type-scale", base=21, ratio="perfect-fourth")
        self.op(type="style-define", name="kpi", settings={"size": 92})
        self.op(type="style-define", name="label", settings={"size": 19})
        self.op(type="style-define", name="tick", settings={"size": 16, "color": "@muted"})
        self.op(type="style-define", name="poster-title", settings={"size": 150})
        self.op(type="style-define", name="tight", kind="paragraph", settings={"spacing": 6})
        self.op(type="grid", name="g", columns=COLS, rows=1, margin=M, gutter=GUTTER)
        self.op(type="variable", name="eyebrow", value=self.d["eyebrow"])
        self.op(type="variable", name="title", value=self.d["title"])
        self.op(type="variable", name="region", value=self.d["region"])
        self.flush()

    # ---------------------------------------------------------------- header
    def header(self):
        self.op(type="guide", name="kpi-top", axis="y", position=760)
        self.op(type="guide", name="header-end", axis="y", position=1080)
        self.op(type="solid", name="night-band", width=W, height=1080, x=0, y=0, color="@night")
        # faint decorative sun rays: a repeated thin bar, clipped by a circle
        self.op(type="shape", shape="ellipse", name="sun", width=760, height=760, x=980, y=-260, fill="@night-2")
        self.op(type="shape", shape="rectangle", name="ray", width=800, height=3, x=960, y=-240, fill="alpha(@solar, 0.35)")
        rays = self.repeat("ray", 40, dy=19)
        self.op(type="group", name="rays", targets=rays)
        self.op(type="clip", target="rays", base="sun")

        self.text("eyebrow", "${eyebrow}", "caption", color="@solar", font="dm-mono-500")
        self.op(type="constrain", target="eyebrow", constraints={"left": "guide:g-x1-start.left", "top": "canvas.top+104"})
        self.text("title", "${title}", "poster-title", color="@night-ink", font="heading", spacing=0)
        self.op(type="constrain", target="title", constraints={"left": "guide:g-x1-start.left-6", "top": "eyebrow.bottom+28"})
        self.text("deck", self.d["deck"], "lead", color="@night-muted")
        self.op(type="style-apply", target="deck", name="tight", kind="paragraph")
        self.op(type="text-layout", target="deck", width=round(span(1, 8)), height=200)
        self.op(type="constrain", target="deck", constraints={"left": "guide:g-x1-start.left", "top": "title.bottom+40"})
        self.flush()

        # KPI cards: three 4-column cards with a 32 px gutter
        accents = ["@renewable", "@solar", "@wind"]
        cards = []
        for i, (num, cap) in enumerate(self.d["kpis"]):
            x = col_x(1 + 4 * i)
            cw = span(1, 4)
            self.op(type="shape", shape="rounded-rectangle", name=f"kpi{i}-card", width=round(cw), height=236,
                    x=round(x), y=760, radius=14, fill="@night-2")
            self.op(type="shape", shape="rectangle", name=f"kpi{i}-bar", width=56, height=6, x=round(x) + 32, y=792,
                    fill=accents[i])
            self.text(f"kpi{i}-num", num, "kpi", x=round(x) + 28, y=806, color="@night-ink", font="heading")
            self.text(f"kpi{i}-cap", cap, "body", color="@night-muted")
            self.op(type="style-apply", target=f"kpi{i}-cap", name="tight", kind="paragraph")
            self.op(type="constrain", target=f"kpi{i}-cap",
                    constraints={"left": f"kpi{i}-card.left+32", "bottom": f"kpi{i}-card.bottom-30"})
            self.op(type="group", name=f"kpi{i}", targets=[f"kpi{i}-card", f"kpi{i}-bar", f"kpi{i}-num", f"kpi{i}-cap"])
            cards.append(f"kpi{i}")
        self.op(type="distribute", targets=cards, axis="horizontal", gap=GUTTER)
        self.op(type="group", name="kpis", targets=cards)
        self.op(type="constrain", target="kpis", constraints={"left": "guide:g-x1-start.left", "top": "guide:kpi-top.top"})
        self.flush()

    # ---------------------------------------------------------------- section heading helper
    def section_head(self, key, number, title, sub, guide_y, col_from=1, col_to=12, style="headline"):
        self.op(type="guide", name=f"sec-{key}", axis="y", position=guide_y)
        gx = f"g-x{col_from}-start"
        self.op(type="shape", shape="rectangle", name=f"{key}-rule", width=round(span(col_from, col_to)), height=3, fill="@ink")
        self.op(type="constrain", target=f"{key}-rule", constraints={"left": f"guide:{gx}.left", "top": f"guide:sec-{key}.top"})
        self.text(f"{key}-num", number, "lead", color="@accent-text", font="dm-mono-500")
        self.op(type="constrain", target=f"{key}-num", constraints={"left": f"guide:{gx}.left", "top": f"{key}-rule.bottom+26"})
        self.text(f"{key}-title", title, style, font="heading")
        self.op(type="constrain", target=f"{key}-title", constraints={"left": f"{key}-num.right+18", "top": f"{key}-rule.bottom+12"})
        self.text(f"{key}-sub", sub, "body", color="@muted")
        self.op(type="constrain", target=f"{key}-sub", constraints={"left": f"{key}-title.left", "top": f"{key}-title.bottom+10"})

    # ---------------------------------------------------------------- bar chart
    def bar_chart(self):
        d = self.d
        rows = sorted(d["countries"], key=lambda r: -r[2])
        n = len(rows)
        self.section_head("a", "01", "Who's leading the switch",
                          f"Renewable share of electricity generation, 2025, with the 2015 level marked", 1160)
        self.flush()
        top = 1160 + 210
        row_h, row_gap = 34, 18
        label_w = span(1, 3)
        plot_x = col_x(4)
        plot_w = round(span(4, 12) - 70)  # leave room for value labels
        plot_h = n * row_h + (n - 1) * row_gap
        # legend, top right of the chart
        self.op(type="shape", shape="rounded-rectangle", name="lg-a-bar", width=26, height=14, radius=3, fill="@renewable")
        self.text("lg-a-bar-t", "2025 share", "caption", color="@muted")
        self.op(type="shape", shape="rectangle", name="lg-a-tick", width=4, height=22, fill="@ink")
        self.text("lg-a-tick-t", "2015 level", "caption", color="@muted")
        self.op(type="constrain", target="lg-a-tick-t", constraints={"right": "guide:g-x12-end.left", "bottom": "guide:sec-a.top+170"})
        self.op(type="constrain", target="lg-a-tick", constraints={"right": "lg-a-tick-t.left-10", "center-y": "lg-a-tick-t.center-y"})
        self.op(type="constrain", target="lg-a-bar-t", constraints={"right": "lg-a-tick.left-28", "center-y": "lg-a-tick-t.center-y"})
        self.op(type="constrain", target="lg-a-bar", constraints={"right": "lg-a-bar-t.left-10", "center-y": "lg-a-tick-t.center-y"})
        self.op(type="group", name="legend-a", targets=["lg-a-bar", "lg-a-bar-t", "lg-a-tick", "lg-a-tick-t"])

        # ---- plot group: frame defines 100 %, bars are sized as a percentage of it
        self.op(type="shape", shape="rectangle", name="a-frame", width=plot_w, height=plot_h + 24, x=plot_x, y=top - 12,
                fill="transparent")
        self.op(type="shape", shape="rectangle", name="a-grid", width=1, height=plot_h + 24, x=plot_x, y=top - 12, fill="@rule")
        a_grid = self.repeat("a-grid", 5, dx=(plot_w - 1) / 4)
        for i, (name, v15, v25) in enumerate(rows):
            y = top + i * (row_h + row_gap)
            self.op(type="shape", shape="rectangle", name=f"a-bar{i}", width=10, height=row_h, x=plot_x, y=y, fill="@renewable")
        self.flush()
        members = ["a-frame", *a_grid] + [f"a-bar{i}" for i in range(n)]
        self.op(type="group", name="a-plot", targets=members)
        for i, (name, v15, v25) in enumerate(rows):
            # percentage of the parent group == percentage of renewable share
            self.op(type="resize", target=f"a-bar{i}", width=f"{v25}%", height=row_h)
            self.op(type="shape", shape="rectangle", name=f"a-tick{i}", width=4, height=row_h + 12,
                    x=round(plot_x + plot_w * v15 / 100) - 2, y=top + i * (row_h + row_gap) - 6, fill="@ink")
        self.op(type="group", name="a-ticks", targets=[f"a-tick{i}" for i in range(n)])
        self.flush()
        # labels and values (top level, constrained to bars)
        for i, (name, v15, v25) in enumerate(rows):
            y = top + i * (row_h + row_gap)
            self.text(f"a-name{i}", name, "label", font="dm-sans-700")
            self.op(type="constrain", target=f"a-name{i}", constraints={"left": "guide:g-x1-start.left", "center-y": f"canvas.top+{y + row_h / 2:.0f}"})
            bar_end = plot_x + plot_w * v25 / 100
            if v25 > 90:  # would collide with the 100 % gridline: set the value inside the bar
                self.text(f"a-val{i}", f"{v25:.1f}%", "label", font="dm-mono-500", color="@on-accent")
                self.op(type="constrain", target=f"a-val{i}", constraints={"right": f"canvas.left+{bar_end - 14:.0f}", "center-y": f"canvas.top+{y + row_h / 2:.0f}"})
            else:
                self.text(f"a-val{i}", f"{v25:.1f}%", "label", font="dm-mono-500")
                self.op(type="constrain", target=f"a-val{i}", constraints={"left": f"canvas.left+{bar_end + 12:.0f}", "center-y": f"canvas.top+{y + row_h / 2:.0f}"})
        # axis labels under the plot
        for k in range(5):
            self.text(f"a-ax{k}", f"{k * 25}%", "tick", font="dm-mono-500")
            self.op(type="constrain", target=f"a-ax{k}", constraints={"center-x": f"canvas.left+{plot_x + plot_w * k / 4:.0f}", "top": f"canvas.top+{top + plot_h + 22}"})
        # reference line + annotation (leader line)
        ref_label, ref = d["reference"]
        rx = plot_x + plot_w * ref / 100
        self.op(type="pen", name="a-ref", points=[[3, 0], [3, plot_h + 60]], smooth=False, stroke="@accent", stroke_width=2,
                fill="transparent", x=round(rx) - 3, y=top - 36, width=6, height=plot_h + 60)
        self.text("a-ref-t", f"{ref_label} {ref:.1f}%", "caption", color="@accent-text", font="dm-sans-700")
        self.op(type="constrain", target="a-ref-t", constraints={"left": "a-ref.right+6", "top": "a-ref.top-4"})
        self.flush()
        self.n_rows = n
        self.a_bottom = top + plot_h + 60
        return top, plot_x, plot_w, plot_h

    # ---------------------------------------------------------------- line / area chart
    def line_chart(self):
        d = self.d
        sec = self.a_bottom + 110
        self.section_head("b", "02", "A decade of steady climbing",
                          f"{d['region']}: renewable share of electricity, and the part from solar and wind", sec)
        self.flush()
        top = sec + 200
        px, pw, ph = col_x(1) + 64, round(span(1, 12) - 64 - 150), 540
        ymax = math.ceil(max(d["renewables"]) * 1.15 / 10) * 10
        self.ymax = ymax
        n = len(YEARS)

        def pt(i, v):
            return pw * i / (n - 1), ph - ph * v / ymax

        # y grid via one repeated hairline
        steps = 4
        self.op(type="shape", shape="rectangle", name="b-grid", width=pw, height=1, x=px, y=top, fill="@rule")
        b_grid = self.repeat("b-grid", steps + 1, dy=(ph - 1) / steps)
        self.op(type="shape", shape="rectangle", name="b-base", width=pw, height=3, x=px, y=top + ph - 1, fill="@ink")
        for k in range(steps + 1):
            v = ymax * (steps - k) / steps
            self.text(f"b-yl{k}", f"{v:.0f}%", "tick", font="dm-mono-500", align="right")
            self.op(type="constrain", target=f"b-yl{k}", constraints={"right": f"canvas.left+{px - 14}", "center-y": f"canvas.top+{top + ph * k / steps:.0f}"})
        for i, yr in enumerate(YEARS):
            self.text(f"b-x{i}", str(yr), "tick", font="dm-mono-500")
            self.op(type="constrain", target=f"b-x{i}", constraints={"center-x": f"canvas.left+{px + pw * i / (n - 1):.0f}", "top": f"canvas.top+{top + ph + 16}"})
        # area for total renewables (single-contour Bézier-free path)
        pts = [pt(i, v) for i, v in enumerate(d["renewables"])]
        path = f"M0 {ph} " + " ".join(f"L{x:.1f} {y:.1f}" for x, y in pts) + f" L{pw} {ph} Z"
        self.op(type="shape", shape="path", name="b-area", width=pw, height=ph, x=px, y=top, path=path,
                fill="alpha(@renewable, 0.22)")
        # second area for solar + wind
        pts2 = [pt(i, v) for i, v in enumerate(d["solar_wind"])]
        path2 = f"M0 {ph} " + " ".join(f"L{x:.1f} {y:.1f}" for x, y in pts2) + f" L{pw} {ph} Z"
        self.op(type="shape", shape="path", name="b-area2", width=pw, height=ph, x=px, y=top, path=path2,
                fill="mix(@solar, @background, 45%)")
        # lines drawn with the pen (padded so the stroke is not clipped at the layer edge)
        pad = 8
        for nm, series, colr in (("b-line", pts, "@renewable"), ("b-line2", pts2, "@solar")):
            self.op(type="pen", name=nm, points=[[x + pad, y + pad] for x, y in series], smooth=False,
                    stroke=colr, stroke_width=5, fill="transparent", x=px - pad, y=top - pad, width=pw + 2 * pad, height=ph + 2 * pad)
        # end-point dots and direct labels (instead of a separate legend for this chart)
        for nm, series, colr, label, vals in (("b-end", pts, "@renewable", "All renewables", d["renewables"]),
                                              ("b-end2", pts2, "@solar", "Solar + wind", d["solar_wind"])):
            x, y = series[-1]
            self.op(type="shape", shape="ellipse", name=nm, width=18, height=18, x=round(px + x - 9), y=round(top + y - 9),
                    fill=colr, stroke="@background", stroke_width=3)
            self.text(f"{nm}-v", f"{vals[-1]:.1f}%", "lead", font="dm-sans-700")
