def qa(p, slug, n_rows, report, height):
    r = {}
    # spacing: KPI cards, bar rows, legend rows
    r["kpi_cards"] = p.measure_spacing(targets=["kpi0", "kpi1", "kpi2"], axis="horizontal", expected=GUTTER, tolerance=1)
    r["bars"] = p.measure_spacing(targets=[f"a-bar{i}" for i in range(n_rows)], axis="vertical", expected=18, tolerance=0)
    r["donut_legend"] = p.measure_spacing(targets=[f"c-lg{i}" for i in range(6)], axis="vertical", expected=18, tolerance=0)
    # Label boxes have different heights (descenders), so equal *edge* gaps are not expected here;
    # the bars themselves carry the rhythm.
    r["axis_labels"] = p.measure_spacing(targets=[f"b-x{i}" for i in range(11)], axis="horizontal", tolerance=12)
    r["section_c_heads"] = p.measure_spacing(targets=["c-title", "d-title"], axis="horizontal")
    rules = [
        "canvas.width == 1600",
        f"canvas.height == {height}",
        "text.f-note.font-size >= 14",
        "layer.kpis.bounds within canvas",
        "layer.a-plot.bounds within canvas",
        "layer.b-plot.bounds within canvas",
        "layer.donut-block.bounds within canvas",
        "layer.d-grid.bounds within canvas",
        "layer.f-palette.bounds within canvas",
        "layer.legend-a.exists",
    ]
    from vixl.validation import validate

    r["validate"] = validate(p, rules=rules)
    # validate() also adds a bounds rule for EVERY layer; the decorative sun/rays bleed off the top on purpose.
    bleed = {"layer.sun.bounds within canvas", "layer.rays.bounds within canvas"}
    r["validate_excluding_bleed"] = all(c["passed"] or c["severity"] == "warning" or c["rule"] in bleed
                                        for c in r["validate"]["checks"])
    # Documented mismatch: font-size assertions read the layer's own size, not its linked character style.
    r["font_size_style_mismatch"] = {
        "style_size": p.state["character_styles"]["poster-title"]["size"],
        "layer_size": p.layer("title")["size"],
        "assert text.title.font-size >= 120": validate(p, rules=["text.title.font-size >= 120"])["checks"][-1]["passed"],
    }
    import time

    timings = {}
    t = time.time()
    # A poster is read at full size, so legibility is judged at a 1080 px "thumbnail", not 320 px.
    r["check"] = p.check(checks=["bounds", "overlap", "safe_area", "legibility", "color_vision"], safe_area=64,
                         thumbnail_width=1080)
    timings["check_without_contrast"] = round(time.time() - t, 1)
    # Contrast measures each text layer against a fresh render (~10-20 s per layer on this
    # 1600 px-wide poster), so it is run on a representative subset of text layers.
    contrast_targets = ["eyebrow", "title", "deck", "kpi0-cap", "a-sub", "a-name0", "a-ref-t", "b-yl0",
                        "b-n0-t", "c-lg0-l", "d-note", "f-note"]
    t = time.time()
    r["check_contrast"] = p.check(checks=["contrast"], targets=contrast_targets)
    timings["contrast_subset"] = round(time.time() - t, 1)
    t = time.time()
    r["check_social"] = p.check(artboard="social", comp="social", checks=["bounds", "overlap", "color_vision"])
    timings["check_social"] = round(time.time() - t, 1)
    r["timings"] = timings
    r["spacing_social"] = p.measure_spacing(targets=["s-eyebrow", "s-title"], axis="vertical", artboard="social", comp="social")
    report[slug] = r
    summary = {
        "spacing": {k: r[k]["passed"] for k in ("kpi_cards", "bars", "donut_legend", "axis_labels")},
        "validate": r["validate"]["valid"],
        "validate_excluding_bleed": r["validate_excluding_bleed"],
        "failed_rules": [c["rule"] for c in r["validate"]["checks"] if not c["passed"]],
        "check": {"passed": r["check"]["passed"], "errors": r["check"]["errors"], "warnings": r["check"]["warnings"]},
        "contrast": {"passed": r["check_contrast"]["passed"], "errors": r["check_contrast"]["errors"]},
        "timings": r["timings"],
        "check_social": {"passed": r["check_social"]["passed"], "errors": r["check_social"]["errors"],
                         "warnings": r["check_social"]["warnings"]},
    }
    print("  QA:", json.dumps(summary))
    return r


def series_separation(p):
    """Our own colour-vision test: min pairwise distance of the data swatches after simulation.
    vixl's colour_vision check only covers text, so chart fills are measured here."""
    from PIL import Image

    from vixl.colors import resolve_expression, to_rgba8

    keys = ["solar", "wind", "hydro", "other", "nuclear", "fossil", "renewable"]
    swatches = p.state["swatches"]

    def resolve(c):
        return to_rgba8(resolve_expression(c, swatches))[:3]

    cols = {k: resolve(swatches[k]) for k in keys}
    out = {}
    for kind in ("normal", "deuteranopia", "protanopia", "tritanopia"):
        img = Image.new("RGBA", (len(keys), 1))
        for i, k in enumerate(keys):
            img.putpixel((i, 0), tuple(int(v) for v in cols[k]) + (255,))
        sim = img if kind == "normal" else simulate_vision(img, kind)
        px = [sim.getpixel((i, 0))[:3] for i in range(len(keys))]
        worst = None
        donut = keys[:6]
        for i in range(len(donut)):
            for j in range(i + 1, len(donut)):
                dist = math.dist(px[i], px[j])
                if worst is None or dist < worst[0]:
                    worst = (round(dist, 1), donut[i], donut[j])
        out[kind] = worst
    return out


